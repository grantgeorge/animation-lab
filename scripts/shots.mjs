import { chromium } from "@playwright/test";
const out = process.argv[2];
const base = process.env.BASE_URL ?? "http://localhost:3123";
const browser = await chromium.launch({ args: ["--use-angle=metal", "--enable-gpu", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
const errors = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(`${m.type()}: ${m.text()}`); });
page.on("pageerror", (e) => errors.push(`pageerror: ${e.message}`));
const extra = process.env.FREEZE ? `&freeze=${process.env.FREEZE}` : "";
await page.goto(`${base}/labs/lens-and-framing?e2e=1&quality=high${extra}`, { waitUntil: "networkidle" });
await page.waitForFunction(() => !!window.__animationLab, null, { timeout: 30000 });
await page.waitForTimeout(1500);
const settle = () => page.evaluate(() => window.__animationLab.settle());
await settle();
const renderer = await page.evaluate(() => { const c = document.createElement("canvas").getContext("webgl2"); const e = c.getExtension("WEBGL_debug_renderer_info"); return e ? c.getParameter(e.UNMASKED_RENDERER_WEBGL) : "n/a"; });
await page.screenshot({ path: `${out}/01-default-50mm.png` });
await page.keyboard.press("Digit2"); await page.waitForTimeout(400); await settle();
await page.screenshot({ path: `${out}/02-fixed-24mm.png` });
await page.keyboard.press("Digit5"); await page.waitForTimeout(400); await settle();
await page.screenshot({ path: `${out}/03-fixed-85mm.png` });
await page.keyboard.press("Digit4"); await page.keyboard.press("KeyM"); await page.waitForTimeout(300);
await page.keyboard.press("Digit2"); await page.waitForTimeout(1500); await settle();
await page.screenshot({ path: `${out}/04-match-24mm.png` });
await page.keyboard.press("Digit5"); await page.waitForTimeout(1500); await settle();
await page.screenshot({ path: `${out}/05-match-85mm.png` });
await page.keyboard.press("KeyV"); await page.waitForTimeout(800); await settle();
await page.screenshot({ path: `${out}/06-monitor-primary.png` });
const state = await page.evaluate(() => ({ m: window.__animationLab.measurements(), f: window.__animationLab.frames().at(-1) }));
console.log(JSON.stringify({ renderer, errors: errors.slice(0, 15), focal: state.m.focalMm, dist: state.m.distanceM, frac: state.m.subjectFraction, frame: { passes: state.f.passes, calls: state.f.calls, tris: state.f.triangles, phases: state.f.phases } }, null, 1));
await browser.close();
