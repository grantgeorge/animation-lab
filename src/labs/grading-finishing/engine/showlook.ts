import type { SceneId } from "@/labs/lens-and-framing/config";
import { NEUTRAL_GRADE, applyChain, resolveGrade, type GradeParams, type ResolvedGrade } from "./grade";
import { NEUTRAL_LOOK, type Look } from "./look";
import { sampleLut, toCube } from "./lut";
import { NEUTRAL_MATCH, matchToGrade, processPixels, sigDelta, signature, type Pixels, type Signature } from "./match";
import { SHOTS, SHOW_STEPS, getShot, overrideFinish, isOverrideActive, type ShowShotState, type ShowStep } from "./shots";
import type { RGB } from "./color";

const atLeast = (step: ShowStep, s: ShowStep) => SHOW_STEPS.indexOf(step) >= SHOW_STEPS.indexOf(s);

export const overrideGrade = (st: ShowShotState): GradeParams => ({ ...NEUTRAL_GRADE, ...st.override.grade });

/** The grade layers a shot passes through at a given exercise step (source drift first). */
export function shotLayers(id: SceneId, step: ShowStep, look: Look, st: ShowShotState, opts: { includeDrift?: boolean } = {}): GradeParams[] {
  const layers: GradeParams[] = [];
  if (opts.includeDrift !== false) layers.push({ ...NEUTRAL_GRADE, ...getShot(id).drift });
  if (atLeast(step, "match")) layers.push(matchToGrade(st.match));
  if (atLeast(step, "look")) layers.push(look.grade);
  if (atLeast(step, "override") && isOverrideActive(st.override)) layers.push(overrideGrade(st));
  return layers;
}

export const resolveLayers = (layers: GradeParams[]): ResolvedGrade[] => layers.map(resolveGrade);

/**
 * A shot's leftover drift at a step: its signature minus the signature of its own clean render
 * passed through the same show look and override. Only unintended differences remain: a perfect
 * balance gives zero whatever the look, and an intentional override is part of the target.
 */
export function shotResidual(px: Pixels, id: SceneId, step: ShowStep, look: Look, st: ShowShotState): Signature {
  const actual = signature(processPixels(px, resolveLayers(shotLayers(id, step, look, st))));
  const target = signature(processPixels(px, resolveLayers(shotLayers(id, step, look, { match: NEUTRAL_MATCH, override: st.override }, { includeDrift: false }))));
  return sigDelta(actual, target);
}

/** The finishing a shot gets at a step: none before the show look, the show finish (plus override) after. */
export function shotFinish(step: ShowStep, look: Look, st: ShowShotState) {
  if (!atLeast(step, "look")) return NEUTRAL_LOOK.finish;
  return atLeast(step, "override") ? overrideFinish(look.finish, st.override) : look.finish;
}

/** A 33³ .cube of a grade chain (no drift): what you load on the clip in Resolve. */
export function chainCube(layers: GradeParams[], title: string, size = 33): string {
  const chain = resolveLayers(layers);
  const lut = sampleLut((c: RGB) => applyChain(c, chain), size);
  return toCube(lut, size, title, [
    "Generated by Animation Lab / Grading & Finishing.",
    "Input and output: Rec.709 / sRGB display-referred code values (apply to the clip as delivered).",
    "Grade only: grain, halation, bloom, lens, vignette and stylization cannot live in a LUT.",
  ]);
}

export interface ShowLookDoc {
  format: "animation-lab.show-look";
  version: 1;
  name: string;
  note: string;
  show: Look & { lookId: string | null };
  shots: Record<string, { match: ShowShotState["match"]; override: ShowShotState["override"] | null }>;
}

export function showLookDoc(name: string, look: Look, lookId: string | null, shots: Record<SceneId, ShowShotState>): ShowLookDoc {
  return {
    format: "animation-lab.show-look",
    version: 1,
    name,
    note: "Show default + per-shot balance and overrides. Order per shot: balance (match) → show grade → shot override → stylize → finishing.",
    show: { ...look, lookId },
    shots: Object.fromEntries(SHOTS.map((s) => [s.id, { match: shots[s.id].match, override: isOverrideActive(shots[s.id].override) ? shots[s.id].override : null }])),
  };
}
